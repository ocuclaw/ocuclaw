function mapHermesActivityToolName(toolName) {
  if (typeof toolName !== "string" || !toolName) return toolName;
  if (!Object.prototype.hasOwnProperty.call(HERMES_TOOL_NAME_SHIM, toolName)) {
    return toolName;
  }
  const mapped = HERMES_TOOL_NAME_SHIM[toolName];
  return typeof mapped === "string" && mapped ? mapped : toolName;
}

function normalizeHermesActivityToolPayload(payload) {
  if (!payload || typeof payload !== "object" || Array.isArray(payload)) {
    return payload;
  }
  if (payload.origin !== "tool" || typeof payload.tool !== "string") {
    return payload;
  }
  const mapped = mapHermesActivityToolName(payload.tool);
  if (mapped === payload.tool) return payload;
  return {
    ...payload,
    hermesTool: payload.tool,
    tool: mapped,
  };
}

