const NONE_CRITERION =
  "no picture plainly names the subject, and a loose or generic fit counts as none";

const TITLE_ICON_QUESTIONS = Object.freeze({
  [TITLE_ICON_QUESTION]: Object.freeze({
    type: "choice",
    instructions: Object.freeze({
      question:
        "A small picture can sit in front of the title of the glasses screen made for this. Which picture names its subject at a glance? A loose or generic fit is worse than no picture, so pick none unless one plainly fits.",
      inspect: "wearer_said",
    }),
    criteria: Object.freeze({ ...TITLE_ICON_CRITERIA, none: NONE_CRITERION }),
  }),
});

function titleIconOf(answers     )                {
  const answer = answers && typeof answers === "object" ? answers[TITLE_ICON_QUESTION] : null;
  const choice = answer && typeof answer.choice === "string" ? answer.choice : null;
  if (!choice || choice === "none") return null;
  return Object.prototype.hasOwnProperty.call(TITLE_ICON_CRITERIA, choice) ? choice : null;
}

